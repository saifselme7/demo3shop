const categoryMap = new Map(SEED_CATEGORIES.map((category) => [category.slug, category]));

interface ProductDraft {
  id: string;
  categorySlug: string;
  name: string;
  slug: string;
  description: string;
  price: number;
  oldPrice?: number;
  discountPercent?: number;
  sizes?: string[];
  colors?: string[];
  stock: number;
  isFeatured?: boolean;
  displayOrder: number;
  images: string[];
}

const product = (draft: ProductDraft): Product => {
  const category = categoryMap.get(draft.categorySlug);
  if (!category) throw new Error(`Unknown category: ${draft.categorySlug}`);

  return {
    ...draft,
    categoryId: category.id,
    categoryName: category.name,
    oldPrice: draft.oldPrice ?? null,
    discountPercent: draft.discountPercent ?? null,
    sizes: draft.sizes ?? ['M', 'L', 'XL'],
    colors: draft.colors ?? ['أسود'],
    isActive: true,
    isFeatured: draft.isFeatured ?? false,
  };
};

